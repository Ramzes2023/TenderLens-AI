def test_dialect_literals_parameters_conflict_and_types():
    assert postgres_sql("SELECT '?' AS literal WHERE id=?") == "SELECT '?' AS literal WHERE id=%s"
    assert postgres_sql("SELECT 'INTEGER % ?' WHERE id=?") == "SELECT 'INTEGER %% ?' WHERE id=%s"
    assert postgres_sql("INSERT OR IGNORE INTO monitor_seen VALUES (?)").endswith("VALUES (%s) ON CONFLICT DO NOTHING")
