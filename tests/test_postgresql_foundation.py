def test_import_dry_run_preserves_source_and_destination(sqlite_database, tmp_path):
    seeded_source(sqlite_database)
    destination = empty_destination(tmp_path)
    try:
        before = sqlite_database.settings.path.read_bytes(), destination.settings.path.read_bytes()
        fixture = ImportDestinationFixture(destination)
        counts = import_sqlite(sqlite_database.settings.path, fixture, dry_run=True)
        assert counts["auth_accounts"] == 1
        assert before == (sqlite_database.settings.path.read_bytes(), destination.settings.path.read_bytes())
        assert not any(sql.startswith(("INSERT", "CREATE", "BEGIN")) or "setval(" in sql for sql in fixture.statements)
    finally:
        destination.close()


def test_import_preserves_every_value_and_refuses_second_execution(sqlite_database, tmp_path):
    seeded_source(sqlite_database)
    destination = empty_destination(tmp_path)
    try:
        fixture = ImportDestinationFixture(destination)
        counts = import_sqlite(sqlite_database.settings.path, fixture, dry_run=False)
        with closing(sqlite_database.connect()) as source, closing(destination.connect()) as target:
            for table in TABLES:
                assert [tuple(row) for row in source.execute(f'SELECT * FROM "{table}"')] == [tuple(row) for row in target.execute(f'SELECT * FROM "{table}"')]
                assert target.execute(f'SELECT COUNT(*) FROM "{table}"').fetchone()[0] == counts[table]
            assert target.execute("PRAGMA foreign_key_check").fetchall() == []
        with pytest.raises(StorageError, match="already been imported"):
            import_sqlite(sqlite_database.settings.path, fixture, dry_run=False)
    finally:
        destination.close()


