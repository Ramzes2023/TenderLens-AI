class FakeRaw:
    def __init__(self):
        self.calls = []
        self.commits = self.rollbacks = self.closes = 0
        self.fail = None

    def execute(self, sql, params=None):
        self.calls.append((sql, params))
        if self.fail:
            raise self.fail
        result = MagicMock()
        result.rowcount = 1
        result.fetchone.return_value = {"id": 42} if "RETURNING" in sql else {"value": 1}
        result.fetchall.return_value = [{"id": 42}]
        return result

    def cursor(self):
        return MagicMock()

    def commit(self):
        self.commits += 1

    def rollback(self):
        self.rollbacks += 1

    def close(self):
        self.closes += 1


class FakePool:
    def __init__(self, **kwargs):
        self.kwargs = kwargs
        self.raw = FakeRaw()
        self.returned = []
        self.opened = self.closed = 0

    def open(self, **kwargs):
        self.opened += 1

    def getconn(self, **kwargs):
        return self.raw

    def putconn(self, raw):
        self.returned.append(raw)

    def close(self):
        self.closed += 1


def fake_database(factory=FakePool):
    return Database(parse_database_settings("postgresql://user:secret@localhost/test", pool_min=2, pool_max=5), pool_factory=factory)


def test_pool_reuse_insert_ids_safe_release_shutdown():
    database = fake_database()
    database.open()
    pool = database.pool
    assert pool.kwargs["min_size"] == 2 and pool.kwargs["max_size"] == 5
    assert pool.opened == 1
    with closing(database.connect()) as conn:
        with conn:
            conn.execute("BEGIN IMMEDIATE")
            cursor = conn.execute("INSERT INTO auth_accounts(email) VALUES (?)", ("synthetic@example.test",))
            assert cursor.lastrowid == 42
            assert "RETURNING id" in pool.raw.calls[-1][0]
            assert pool.raw.calls[-1][1] == ("synthetic@example.test",)
    assert pool.raw.commits == 1 and pool.raw.rollbacks == 1
    assert len([sql for sql, _ in pool.raw.calls if "pg_advisory_xact_lock" in sql]) == 1
    with closing(database.connect()) as conn:
        assert conn.execute("SELECT 1").fetchone()[0] == 1
    assert pool.opened == 1 and len(pool.returned) == 2
    database.close()
    database.close()
    assert pool.closed == 1
    with pytest.raises(StorageError):
        database.connect()


